const fs = require('node:fs');
const path = require('node:path');
const babel = require('@babel/core');
const directory = path.resolve(__dirname, '../../public/signage');
const sources = ['online-boot', 'renderer', 'schedule', 'player'];
const source = sources.map(name => fs.readFileSync(path.join(directory, name + '.js'), 'utf8')).join('\n;\n');
const result = babel.transformSync(source, {
    sourceType: 'script', babelrc: false, configFile: false,
    presets: [[require.resolve('@babel/preset-env'), { targets: { chrome: '49' }, modules: false }]],
});
fs.writeFileSync(path.join(directory, 'online-player.js'), '// Generated by scripts/signage/build-online-player.cjs\n' + result.code + '\n');
